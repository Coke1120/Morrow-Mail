const invokeSet = new Set(INVOKE);
const eventSet = new Set(EVENTS);

contextBridge.exposeInMainWorld("morrow", {
  reportUpdateReady() { ipcRenderer.send("host:updateStartupReady"); },
  replyUpdatePreparation(payload) {
    if (typeof payload?.nonce === "string" && typeof payload.ok === "boolean") {
      ipcRenderer.send("host:updatePrepared", { nonce: payload.nonce, ok: payload.ok });
    }
  },
  replyQuitScheduledShown(payload) {
    if (typeof payload?.nonce === "string") {
      ipcRenderer.send("app:quitScheduledShown", { nonce: payload.nonce });
    }
  },
  replyQuitScheduled(payload) {
    const choice = payload && payload.choice;
    if (typeof payload?.nonce === "string" && (choice === "quit" || choice === "stay" || choice === "view")) {
      ipcRenderer.send("app:quitScheduledChoice", { nonce: payload.nonce, choice });
    }
  },
  openComposeWindow(seed) {
    return ipcRenderer.invoke("compose:open", seed);
  },
  pullComposeSeed() {
    return ipcRenderer.invoke("compose:pullSeed");
  },
  allowComposeClose() {
    ipcRenderer.send("compose:allowClose");
  },
  setComposeTitle(title) {
    const text = typeof title === "string" ? title : "";
    return ipcRenderer.invoke("compose:setTitle", text);
  },
  openReaderWindow(seed) {
    return ipcRenderer.invoke("reader:open", seed);
  },
  pullReaderSeed() {
    return ipcRenderer.invoke("reader:pullSeed");
  },
  openTranslateWindow(seed) {
    return ipcRenderer.invoke("translate:open", seed);
  },
  pullTranslateSeed() {
    return ipcRenderer.invoke("translate:pullSeed");
  },
  reportTranslate(payload) {
    return ipcRenderer.invoke("translate:report", payload);
  },
  invoke(channel, payload) {
    if (!invokeSet.has(channel)) {
      return Promise.reject(new Error("Unsupported channel"));
    }
    return ipcRenderer.invoke(channel, payload);
  },
  on(channel, handler) {
    if (!eventSet.has(channel) || typeof handler !== "function") return function () {};
    const wrapped = (_event, data) => handler(data);
    ipcRenderer.on(channel, wrapped);
    return () => ipcRenderer.removeListener(channel, wrapped);
  },
});
