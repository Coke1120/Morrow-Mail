// Real renderer workflow functions with synthetic DOM/IPC; no provider or credentials.
const assert = require('node:assert/strict');
const {renderer} = require('./check-ux-workflows');
async function run() {
  const nodes = new Map();
  const get = id => {
    if (!nodes.has(id)) nodes.set(id,{value:'',type:'text',textContent:'',open:false,hidden:false,checked:false,children:[],options:[],classList:{toggle(){}},focus(){},scrollIntoView(){},setAttribute(){},replaceChildren(...items){this.children=items;this.options=items;},append(...items){this.children.push(...items);this.options=this.children;}});
    return nodes.get(id);
  };
  const ui = renderer({document:{getElementById:get,createElement:()=>({})}});
  ui.run(`state.accounts=[{id:'a',email:'alpha@example.invalid',platform:'imap'},{id:'b',email:'beta@example.invalid',platform:'imap'}];state.accountId='a';state.settingsAccountId='b';`);
  assert.equal(ui.run('settingsAccount().id'),'b');
  get('settings').open=true;
  assert.equal(ui.run('signatureAccount().id'),'b');
  ui.run(`state.composeMeta={accountId:'a'}`);get('compose').open=true;
  assert.equal(ui.run('signatureAccount().id'),'b','Settings signatures retain explicit mailbox even with compose behind Settings');
  ui.run(`oooBaseline=oooSnapshot();askConfirm=async()=>({ok:false});`);
  get('ooo-message').value='Unsaved Beta reply';
  assert.equal(await ui.run(`changeSettingsMailbox('a')`),false);
  assert.equal(ui.run('state.settingsAccountId'),'b');
  assert.equal(get('ooo-message').value,'Unsaved Beta reply');
  ui.run(`globalThis.pending={};call=async(_channel,payload)=>new Promise(resolve=>{pending[payload.accountId]=resolve;});paintVacation=data=>{vacationCache=data;};setOooStatus=()=>{};`);
  const old=ui.run('loadVacation()');ui.run(`state.settingsAccountId='a'`);const current=ui.run('loadVacation()');
  ui.run(`pending.a({accountId:'a',settings:{mode:'disabled'}})`);await current;
  ui.run(`pending.b({accountId:'b',settings:{mode:'always'}})`);await old;
  assert.equal(ui.run('vacationCache.accountId'),'a','stale OOO response cannot retarget the editor');
  assert.match(ui.run(`vacationSummary(null)`),/unknown/);
  assert.match(ui.run(`vacationSummary({supported:true,requiresReconnect:true})`),/permission/);
  assert.match(ui.run(`vacationSummary({supported:true,settings:{mode:'disabled'}})`),/off/);
  assert.match(ui.run(`vacationSummary({provider:'imap',supported:true,settings:{mode:'scheduled',start:'2099-01-02T10:00:00Z',end:'2099-01-03T10:00:00Z'}})`),/2099-01-02 00:00 UTC.*2099-01-04 00:00 UTC/);
  assert.match(ui.run(`runModeLabel({schedule:'interval',everyMinutes:30,nextRunAt:'2099-01-01T08:00:00Z'})`),/Scheduled.*Next run.*open.*relaunch/);
  assert.doesNotMatch(ui.run(`runModeLabel({schedule:'paused',nextRunAt:'2099-01-01T08:00:00Z'})`),/Next run/);
  assert.match(ui.run(`runModeLabel({schedule:'disabled'})`),/On demand/);
  ui.run(`globalThis.calls=[];call=async(channel,params)=>{calls.push({channel,params});return {email:{id:'source',accountId:'b',from:'Sender <sender@example.invalid>',subject:'Original',textBody:'Source'}};};`);
  const description={textContent:''};ui.context.description=description;
  await ui.run(`describeDraftSource(description,{messageId:'source',accountId:'b',to:'wrong@example.invalid'})`);
  assert.match(description.textContent,/beta@example.invalid.*\nSource: Original.*\nAction: Review reply draft.*\nTo: Sender <sender@example.invalid>/);
  assert.doesNotMatch(description.textContent,/wrong@example.invalid/);
  await ui.run(`confirmProposal({id:'p',accountId:'b',messageId:'source',labelName:'Archive'})`);
  assert.equal(ui.run(`calls.filter(row=>row.channel!=='mail:openEmail').length`),0,'canceled proposal confirmation makes no provider call');
  assert.equal(ui.run('updateView({}).status'),'Updates have not been checked yet.');
  assert.equal(ui.run(`updateView({lastCheckedAt:'2026-10-18T08:00:00Z'}).status`),'Up to date.');
  assert.equal(ui.run('updateView({downloaded:true}).install'),true);
  const raw='{"password":"private words", "refresh_token":"private-refresh"} bearer private-bearer sk-proj-1234567890_secret';
  ui.context.raw=raw;
  const redacted=ui.run('redactDebugText(raw)');
  assert.doesNotMatch(redacted,/private words|private-refresh|private-bearer|1234567890_secret/);
  assert.doesNotMatch(require('../host/debug-log').redactDebugText(raw),/private words|private-refresh|private-bearer|1234567890_secret/);
  ui.run(`globalThis.preference=null;globalThis.localStorage={getItem:()=>preference};`);
  assert.equal(ui.run('readNavCollapsed()'),false);
  ui.run(`preference='1'`);assert.equal(ui.run('readNavCollapsed()'),true);
  ui.run(`preference='0'`);assert.equal(ui.run('readNavCollapsed()'),false);
  ui.run(`renderReader=()=>{};renderList=()=>{};state.prefs.conversation=false;showStatus=text=>{globalThis.receipt=text;};call=async channel=>{if(channel==='mail:markRead')throw new Error('Fixture persistence failed');return {email:{id:'read',accountId:'a',unread:true}};};`);
  await ui.run(`openMessage('read',false)`);
  assert.equal(ui.run('state.email.id'),'read');assert.match(ui.run('receipt'),/opened.*not confirmed.*Fixture persistence failed/);
  const vm = require('node:vm'), fs = require('node:fs'), path = require('node:path');
  const events={}, ipc={};
  const updater={on:(name,fn)=>{events[name]=fn;},setFeedURL(){},checkForUpdates:async()=>{}};
  const host={module:{exports:{}},setTimeout(){},setImmediate(){},Date,require(name){
    if(name==='electron')return {app:{isPackaged:true},ipcMain:{handle:(name,fn)=>{ipc[name]=fn;}}};
    if(name==='electron-updater')return {autoUpdater:updater};
    if(name==='./update-auth')return {resolveGithubToken:()=>null,githubFeed:()=>({}),explainUpdateError:e=>e.message,authFailureKind:()=>''};
    throw new Error('Unexpected dependency '+name);
  }};
  vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../host/updater.js'),'utf8'),host);
  host.module.exports.init();host.module.exports.registerIpc();
  assert.equal(host.module.exports.snapshot().lastCheckedAt,null);
  events['checking-for-update']();events.error(new Error('Offline fixture'));
  assert.equal(host.module.exports.snapshot().lastCheckedAt,null,'failed update attempt must not imply a completed check');
  events['checking-for-update']();events['update-not-available']();
  assert.ok(host.module.exports.snapshot().lastCheckedAt);
  assert.equal(updater.autoInstallOnAppQuit,true);
  events['update-downloaded']({version:'fixture'});
  assert.equal(ipc['host:updateInstall']().installing,true);
  console.log('ux-remainder-ok');
}
module.exports={run};
if(require.main===module)run().catch(error=>{console.error(error);process.exitCode=1;});
